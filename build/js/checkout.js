document.addEventListener('DOMContentLoaded', () => {
  renderCheckoutSummary();

  const checkoutForm = document.getElementById('checkout-form');
  const payButton = document.getElementById('razorpay-pay-button');

  if (payButton) {
    payButton.addEventListener('click', handleInitiatePayment);
  }
});

function renderCheckoutSummary() {
  const container = document.getElementById('checkout-items-list');
  const subtotalEl = document.getElementById('checkout-subtotal');
  const shippingEl = document.getElementById('checkout-shipping');
  const totalEl = document.getElementById('checkout-total');
  
  if (!container) return;

  const cart = CartManager.getCart();
  if (cart.length === 0) {
    container.innerHTML = `
      <div style="padding: 2rem 0; text-align: center; color: var(--text-secondary);">
        Your shopping bag is empty. <br><br>
        <a href="shop.html" class="link-arrow">Browse Collection</a>
      </div>
    `;
    if (totalEl) totalEl.textContent = '₹0';
    return;
  }

  let html = '';

  cart.forEach(item => {
    html += `
      <div style="display: flex; gap: 1rem; align-items: center; margin-bottom: 1.25rem; padding-bottom: 1.25rem; border-bottom: 1px solid var(--border);">
        <img src="${item.image}" alt="${item.name}" style="width: 64px; height: 80px; object-fit: cover; border-radius: var(--radius-sm);">
        <div style="flex: 1;">
          <h5 style="font-family: var(--font-body); font-size: 0.9rem; margin-bottom: 0.2rem;">${item.name}</h5>
          <p style="font-size: 0.8rem; color: var(--text-secondary);">${item.color || 'Default'} / ${item.size} • Qty: ${item.qty}</p>
        </div>
        <div style="font-weight: 500; font-size: 0.9rem;">₹${(item.price * item.qty).toLocaleString('en-IN')}</div>
      </div>
    `;
  });

  container.innerHTML = html;

  const { subtotal, shipping, total } = CartManager.calculateTotals();

  if (subtotalEl) subtotalEl.textContent = CartManager.formatPrice(subtotal);
  if (shippingEl) shippingEl.textContent = shipping === 0 ? 'Complimentary' : CartManager.formatPrice(shipping);
  if (totalEl) totalEl.textContent = CartManager.formatPrice(total);

  const payBtn = document.getElementById('razorpay-pay-button');
  if (payBtn && total > 0) {
    payBtn.textContent = `Pay ${CartManager.formatPrice(total)} with Razorpay`;
  }
}

async function handleInitiatePayment(e) {
  e.preventDefault();

  const nameInput = document.getElementById('cust-name');
  const emailInput = document.getElementById('cust-email');
  const phoneInput = document.getElementById('cust-phone');
  const addressInput = document.getElementById('cust-address');

  if (!nameInput?.value || !emailInput?.value || !phoneInput?.value || !addressInput?.value) {
    alert('Please fill in your name, email, contact number, and delivery address.');
    return;
  }

  const cart = CartManager.getCart();
  if (cart.length === 0) {
    alert('Your bag is empty.');
    return;
  }

  const { total: totalAmountInINR } = CartManager.calculateTotals();
  const amountInPaise = Math.round(totalAmountInINR * 100);

  const payBtn = document.getElementById('razorpay-pay-button');
  payBtn.disabled = true;
  payBtn.textContent = 'Preparing Secure Checkout...';

  // Check if Razorpay SDK script is loaded
  if (typeof Razorpay === 'undefined') {
    alert('Razorpay Checkout SDK is still loading. Please check your internet connection.');
    payBtn.disabled = false;
    payBtn.textContent = `Pay ₹${totalAmountInINR.toLocaleString('en-IN')} with Razorpay`;
    return;
  }

  /**
   * IN PRODUCTION:
   * 1. You make a POST request to your backend:
   *    const res = await fetch('/api/orders/create', { method: 'POST', body: JSON.stringify({ items: cart, customer: ... }) });
   *    const { order } = await res.json();
   * 2. You pass order.id and order.key into the options below.
   */

  // Standard Razorpay Checkout Configuration
  const options = {
    key: 'rzp_test_YourTestKeyId123', // Replace with your real Razorpay Test Key ID
    amount: amountInPaise,           // In paise (₹100 = 10000 paise)
    currency: 'INR',
    name: 'GENZSTORE',
    description: `GenZStore Order (${cart.length} garments)`,
    image: 'https://images.unsplash.com/photo-1544441893-675973e31985?auto=format&fit=crop&w=200&q=80',
    // order_id: 'order_DAvL8XXXXX', // Generated by backend via /v1/orders in production

    prefill: {
      name: nameInput.value,
      email: emailInput.value,
      contact: phoneInput.value
    },

    theme: {
      color: '#C88A65' // GenZStore Terracotta accent color
    },

    modal: {
      ondismiss: function() {
        payBtn.disabled = false;
        payBtn.textContent = `Pay ₹${totalAmountInINR.toLocaleString('en-IN')} with Razorpay`;
        CartManager.showToast('Checkout window closed.');
      },
      backdropclose: false
    },

    handler: function(response) {
      /**
       * Payment Succeeded on Razorpay!
       * In production: send to backend /api/orders/verify-payment for HMAC verification.
       * Then redirect to confirmation page.
       */
      // Store for confirmation page fallback
      localStorage.setItem('last_payment_id',   response.razorpay_payment_id  || 'pay_demo_' + Date.now());
      localStorage.setItem('last_order_id',     response.razorpay_order_id    || '');
      localStorage.setItem('last_order_amount', String(totalAmountInINR));
      // Clear bag
      localStorage.removeItem('genzstore_cart');
      // Redirect to confirmation page
      const params = new URLSearchParams({
        payment_id: response.razorpay_payment_id  || '',
        order_id:   response.razorpay_order_id    || '',
        amount:     String(totalAmountInINR)
      });
      window.location.href = `order-confirmation.html?${params.toString()}`;
    }
  };

  // Demo fallback when using placeholder test credentials
  if (!options.key || options.key.includes('YourTestKeyId')) {
    simulateTestPayment(totalAmountInINR, nameInput.value);
    return;
  }

  try {
    const rzp = new Razorpay(options);

    rzp.on('payment.failed', function(response) {
      console.error('Payment failure:', response.error);
      alert(`Payment declined: ${response.error.description}`);
      payBtn.disabled = false;
      payBtn.textContent = `Pay ₹${totalAmountInINR.toLocaleString('en-IN')} with Razorpay`;
    });

    rzp.open();
  } catch (err) {
    console.warn('Razorpay test key notice:', err);
    // Fallback simulation when running locally with placeholder credentials
    simulateTestPayment(totalAmountInINR, nameInput.value);
  }
}

